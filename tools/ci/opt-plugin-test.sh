# Run the lit suite, including the pass-plugin test (test/Plugins), against
# the cudaq-pulse-opt on PATH, as a wheel installs it: build
# examples/custom_passes/cpp against the pinned MLIR toolchain and load it
# into that driver. Needs the toolchain unpacked (tools/fetch-mlir-toolchain.py),
# a C++ compiler, and cmake, ninja and lit on PATH.
#
# Usage: tools/ci/opt-plugin-test.sh [--python PY] [--toolchain PREFIX]

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
python="python3"
toolchain=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --python) python="$2"; shift 2 ;;
    --toolchain) toolchain="$(cd "$2" && pwd)"; shift 2 ;;
    *) echo "error: unknown argument: $1" >&2; exit 2 ;;
  esac
done

if ! opt="$(command -v cudaq-pulse-opt)"; then
  echo "error: cudaq-pulse-opt is not on PATH; install the cudaq-pulse-opt wheel" >&2
  exit 1
fi
if [[ -z "$toolchain" ]]; then
  toolchain="$("$python" "${repo_root}/tools/fetch-mlir-toolchain.py" --print-prefix)"
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

echo "::group::Build the example pass plugin against ${toolchain}"
cmake -S "${repo_root}/examples/custom_passes/cpp" -B "${work}/plugin" -G Ninja \
  -DCMAKE_BUILD_TYPE=Release -DMLIR_DIR="${toolchain}/lib/cmake/mlir"
cmake --build "${work}/plugin"
echo "::endgroup::"
plugins=("${work}"/plugin/lib/PulseExamplePlugin*)

# test/lit.site.cfg.py.in as CMake configures it, with the installed driver.
mkdir -p "${work}/test"
"$python" - "${repo_root}" "$(dirname "$opt")" "${toolchain}/bin" "${plugins[0]}" \
  "${work}/test/lit.site.cfg.py" <<'EOF'
import re
import sys
from pathlib import Path

root, tools, llvm_tools, plugin, out = sys.argv[1:]
text = (Path(root) / "test" / "lit.site.cfg.py.in").read_text()
for key, value in {
    "LIT_SITE_CFG_IN_HEADER": "# Generated by tools/ci/opt-plugin-test.sh.",
    "CUDAQ_PULSE_TOOLS_DIR": tools,
    "CUDAQ_PULSE_SOURCE_DIR": root,
    "LLVM_TOOLS_BINARY_DIR": llvm_tools,
    "CUDAQ_PULSE_EXAMPLE_PLUGIN": plugin,
}.items():
    text = text.replace(f"@{key}@", value)
assert not re.search(r"@\w+@", text), text
Path(out).write_text(text)
EOF

echo "Testing ${opt}"
lit -sv "${work}/test"
